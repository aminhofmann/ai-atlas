// Regenerates components/diagrams/index.ts from the .tsx files in that folder.
// Run after adding a diagram: npm run diagrams
import fs from "node:fs";
const dir = "components/diagrams";
const ids = fs.readdirSync(dir).filter((f) => f.endsWith(".tsx")).map((f) => f.slice(0, -4)).sort();
const ident = (id) => "D_" + id.replace(/-(\w)/g, (_, c) => c.toUpperCase()).replace(/^\w/, (c) => c.toUpperCase());
const out = `// GENERATED by scripts/register-diagrams.mjs — run \`npm run diagrams\` after adding a file.
import type { ComponentType } from "react";
${ids.map((id) => `import ${ident(id)}, { caption as ${ident(id)}_caption } from "./${id}";`).join("\n")}

export type DiagramEntry = { Diagram: ComponentType; caption: string };

/** Concept id → diagram. A concept without an entry simply shows no diagram. */
const DIAGRAMS: Record<string, DiagramEntry> = {
${ids.map((id) => `  "${id}": { Diagram: ${ident(id)}, caption: ${ident(id)}_caption },`).join("\n")}
};

export function getDiagram(id: string): DiagramEntry | null {
  return DIAGRAMS[id] ?? null;
}
`;
fs.writeFileSync(`${dir}/index.ts`, out);
console.log(`registered ${ids.length} diagrams`);
